    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
        EXECUTE 'REVOKE ALL ON SCHEMA fuel_app FROM anon';
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA fuel_app FROM anon';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
        EXECUTE 'REVOKE ALL ON SCHEMA fuel_app FROM authenticated';
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA fuel_app FROM authenticated';
    END IF;
END $$;
